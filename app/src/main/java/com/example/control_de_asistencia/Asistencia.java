package com.example.control_de_asistencia;

public class Asistencia {
    public String nombre;
    public String curso;
    public int edad;
    public String hora;

    public Asistencia(String nombre, String curso, int edad, String hora) {
        this.nombre = nombre;
        this.curso = curso;
        this.edad = edad;
        this.hora = hora;
    }
}
